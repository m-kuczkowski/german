import { readFileSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { put } from "@vercel/blob";

function loadEnv(name) {
  const envFile = process.env.WORTSCHATZ_ENV_FILE || ".env.local";
  const line = readFileSync(resolve(envFile), "utf8")
    .split(/\r?\n/)
    .find((item) => item.startsWith(`${name}=`));
  return line ? line.slice(name.length + 1).replace(/^"|"$/g, "") : undefined;
}

function parseArgs() {
  const args = process.argv.slice(2);
  const value = (name, fallback) => {
    const index = args.indexOf(name);
    return index >= 0 ? args[index + 1] : fallback;
  };
  return {
    audioDir: resolve(value("--audio-dir", "/private/tmp/german-piper-audio")),
    destination: value("--destination", "wortschatz/kokoro-martin-v1"),
    output: resolve(value("--output", "src/data/piperAudioManifest.ts")),
    expectedCards: Number.parseInt(value("--expected-cards", "0"), 10),
  };
}

async function withRetry(action, attempts = 4) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      return await action();
    } catch (error) {
      lastError = error;
      if (attempt === attempts) break;
      await new Promise((resolvePromise) =>
        setTimeout(resolvePromise, 500 * 2 ** (attempt - 1)),
      );
    }
  }
  throw lastError;
}

async function mapConcurrent(items, concurrency, worker) {
  let cursor = 0;
  const results = new Array(items.length);
  const runners = Array.from({ length: Math.min(concurrency, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      results[index] = await worker(items[index], index);
    }
  });
  await Promise.all(runners);
  return results;
}

const options = parseArgs();
const token = process.env.BLOB_READ_WRITE_TOKEN || loadEnv("BLOB_READ_WRITE_TOKEN");
if (!token) throw new Error("Brakuje BLOB_READ_WRITE_TOKEN.");

const manifestPath = resolve(options.audioDir, "manifest.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
if (options.expectedCards > 0 && manifest.cardCount !== options.expectedCards) {
  throw new Error(
    `Oczekiwano ${options.expectedCards} kart, otrzymano ${manifest.cardCount}.`,
  );
}
if (
  !Number.isInteger(manifest.cardCount) ||
  manifest.cardCount < 1 ||
  Object.keys(manifest.clips ?? {}).length !== manifest.cardCount
) {
  throw new Error("Manifest audio jest niepełny albo niespójny.");
}

let completed = 0;
const uploaded = await mapConcurrent(manifest.shards, 6, async (shard) => {
  const filePath = resolve(options.audioDir, "sprites", shard.file);
  const result = await withRetry(() =>
    put(`${options.destination}/${shard.file}`, readFileSync(filePath), {
      access: "public",
      addRandomSuffix: false,
      allowOverwrite: true,
      cacheControlMaxAge: 31_536_000,
      contentType: "audio/webm",
      token,
    }),
  );
  completed += 1;
  console.log(`Blob: ${completed}/${manifest.shards.length}`);
  return result;
});

const firstUrl = new URL(uploaded[0].url);
const basePath = `${firstUrl.origin}/${options.destination}`;
for (const blob of uploaded) {
  if (!blob.url.startsWith(`${basePath}/`)) {
    throw new Error(`Niespójny adres Blob: ${blob.url}`);
  }
}

await withRetry(() =>
  put(
    `${options.destination}/manifest.json`,
    readFileSync(manifestPath),
    {
      access: "public",
      addRandomSuffix: false,
      allowOverwrite: true,
      cacheControlMaxAge: 300,
      contentType: "application/json",
      token,
    },
  ),
);

const compactClips = Object.fromEntries(
  Object.entries(manifest.clips).map(([cardId, clip]) => [
    cardId,
    [clip.shard, clip.start, clip.duration],
  ]),
);
const spritePrefix = typeof manifest.spritePrefix === "string" && manifest.spritePrefix
  ? manifest.spritePrefix
  : "thorsten";
const generated = `// Generated by scripts/upload-piper-audio.mjs.
// Do not edit manually: timings correspond to the uploaded ${manifest.voice} audio sprites.
export const PIPER_AUDIO_BASE_URL = ${JSON.stringify(basePath)};
export const PIPER_AUDIO_MIME_TYPE = ${JSON.stringify(manifest.mimeType)};
export const PIPER_AUDIO_SPRITE_PREFIX = ${JSON.stringify(spritePrefix)};
export const piperAudioClips: Record<string, readonly [number, number, number]> = ${JSON.stringify(compactClips)};
`;
writeFileSync(options.output, generated);

console.log(
  JSON.stringify({
    status: "uploaded",
    cards: manifest.cardCount,
    blobs: uploaded.length + 1,
    bytes: manifest.shards.reduce((sum, shard) => sum + shard.bytes, 0),
    baseUrl: basePath,
    manifest: `${basePath}/manifest.json`,
    generated: options.output,
  }),
);
